#!/usr/bin/env python3
"""Derive the per-benchmark noise band from repeat measurements.

The PR gate compares one measurement against another; a relative tolerance
alone cannot say whether a delta of a few milliseconds is a regression or the
runner breathing. This script turns a set of repeat measurements of unchanged
code into a per-benchmark **noise band**: the slowest delta (in milliseconds)
the same code has been observed to produce, expressed as a multiple of the
measured standard deviation.

It writes the table `scripts/benchmark_ab.py` consumes via `--noise-band`. The
table is data, not policy: re-derive it when the fleet or the benchmark corpus
changes, and review the diff like any other measurement
(see .spec/tech.md § CI Benchmarking).

Usage::

    python scripts/derive_benchmark_noise.py --out scripts/benchmark_noise.json \
        --source https://…/actions/runs/<id>/artifacts/<id> \
        .benchmarks/baselines/main.json run-a.json run-b.json ...

The sample block names the fingerprint, the commits and the artifact URLs the
files came from: the table is a measurement with a date, and a reader has to be
able to tell when the fleet it was measured on has moved. `--source` is
positional in the same order as the files, one URL per file.

Exit codes: 0 derived and written, 2 unusable input (no table written).
"""

from __future__ import annotations

import argparse
import json
import math
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from benchmark_ab import (  # noqa: E402 - path shim above must run first
    MeasurementInvalid,
    fingerprint,
    interpreter,
    samples,
)

DEFAULT_SIGMA_MULTIPLIER = 3.0
DEFAULT_MAX_BAND_PCT = 50.0
DEFAULT_MIN_SAMPLES = 3


def documents(paths: list[Path]) -> list[dict]:
    """Read every repeated measurement, refusing an unreadable one."""
    out = []
    for path in paths:
        try:
            out.append(json.loads(path.read_text()))
        except (OSError, ValueError) as exc:
            raise MeasurementInvalid(f"cannot read {path}: {exc}") from exc
    return out


def require_repeats(docs: list[dict], minimum: int) -> None:
    """One measurement is not a noise estimate; a handful of them is."""
    if len(docs) < minimum:
        raise MeasurementInvalid(
            f"{len(docs)} measurements given; a noise band needs at least {minimum}."
        )
    was_cpu, was_py = fingerprint(docs[0]), interpreter(docs[0])
    for index, doc in enumerate(docs[1:], start=2):
        cpu, py = fingerprint(doc), interpreter(doc)
        if cpu != was_cpu:
            raise MeasurementInvalid(
                f"measurement {index} CPU {cpu} differs from measurement 1 {was_cpu}; "
                "a band cannot mix machines."
            )
        if py != was_py:
            raise MeasurementInvalid(
                f"measurement {index} Python {py} differs from measurement 1 {was_py}."
            )


def rows(docs: list[dict], stat: str) -> dict[str, list[float]]:
    """Selected statistic per benchmark across every repeat, seconds -> ms."""
    per_doc = [samples(doc, stat) for doc in docs]
    names = per_doc[0].keys()
    for index, measured in enumerate(per_doc[1:], start=2):
        if measured.keys() != names:
            raise MeasurementInvalid(
                f"measurement {index} benchmark set differs from measurement 1."
            )
    return {name: [measured[name] * 1000 for measured in per_doc] for name in names}


def band(ms_values: list[float], sigma_multiplier: float, max_band_pct: float) -> dict:
    """Median, standard deviation and gating band for one benchmark."""
    median_ms = statistics.median(ms_values)
    sigma_ms = statistics.pstdev(ms_values)
    band_ms = sigma_ms * sigma_multiplier
    band_pct = band_ms / median_ms * 100 if median_ms else math.inf
    return {
        "median_ms": round(median_ms, 3),
        "sigma_ms": round(sigma_ms, 3),
        "band_ms": round(band_ms, 3),
        "band_pct": round(band_pct, 1),
        # A row whose observed spread already exceeds the band cap has no
        # resolution left: report it, never let it decide a job.
        "gate": band_pct <= max_band_pct,
    }


def derive(
    docs: list[dict],
    *,
    stat: str,
    sigma_multiplier: float,
    max_band_pct: float,
    minimum: int,
    sources: list[str] | None = None,
) -> dict:
    """Build the committed table from validated repeat measurements."""
    require_repeats(docs, minimum)
    measured = rows(docs, stat)
    benchmarks = {
        name: band(values, sigma_multiplier, max_band_pct)
        for name, values in sorted(measured.items())
    }
    return {
        "_comment": (
            "Generated by scripts/derive_benchmark_noise.py from repeat runs of "
            "unchanged code; consumed by scripts/benchmark_ab.py --noise-band. "
            "Re-derive, review the diff, do not hand-edit bands."
        ),
        "stat": stat,
        "sigma_multiplier": sigma_multiplier,
        "max_band_pct": max_band_pct,
        "sample": {
            "measurements": len(docs),
            "cpu": fingerprint(docs[0]),
            "python_version": interpreter(docs[0]),
            "commits": [str((doc.get("commit_info") or {}).get("id")) for doc in docs],
            "sources": list(sources or []),
        },
        "benchmarks": benchmarks,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Derive per-benchmark noise bands from repeat measurements."
    )
    parser.add_argument("files", nargs="+", help="pytest-benchmark result JSON files")
    parser.add_argument("--out", help="write the table here (default: stdout)")
    parser.add_argument("--stat", default="min", choices=("min", "median", "mean"))
    parser.add_argument(
        "--sigma-multiplier", type=float, default=DEFAULT_SIGMA_MULTIPLIER
    )
    parser.add_argument("--max-band-pct", type=float, default=DEFAULT_MAX_BAND_PCT)
    parser.add_argument("--min-samples", type=int, default=DEFAULT_MIN_SAMPLES)
    parser.add_argument(
        "--source",
        action="append",
        default=[],
        metavar="URL",
        help="run and artifact URL a result file came from; repeat once per file, "
        "in the same order as the files.",
    )
    args = parser.parse_args(argv)

    try:
        if not math.isfinite(args.sigma_multiplier) or args.sigma_multiplier <= 0:
            raise MeasurementInvalid("sigma multiplier must be finite and positive.")
        if not math.isfinite(args.max_band_pct) or args.max_band_pct <= 0:
            raise MeasurementInvalid("max band percent must be finite and positive.")
        if args.source and len(args.source) != len(args.files):
            raise MeasurementInvalid(
                f"{len(args.source)} source URL(s) for {len(args.files)} result "
                "file(s); name one source per file, in file order."
            )
        table = derive(
            documents([Path(path) for path in args.files]),
            stat=args.stat,
            sigma_multiplier=args.sigma_multiplier,
            max_band_pct=args.max_band_pct,
            minimum=args.min_samples,
            sources=args.source,
        )
    except MeasurementInvalid as exc:
        print(f"::error title=Noise band not derived::{exc}")
        return 2

    text = json.dumps(table, indent=2, sort_keys=False) + "\n"
    if args.out:
        Path(args.out).write_text(text)
        print(f"wrote {args.out} ({len(table['benchmarks'])} benchmarks)")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
